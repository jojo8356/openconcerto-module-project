-- Reprise des affaires perdues lors des transferts de documents.
--
-- A executer quand le module n'est pas disponible, ou pour verifier a la main ce
-- que fait le menu « Aide > Reprendre les affaires des documents ». Les regles
-- sont identiques (AffairBackfillSupport) : on ne remplit QUE le vide, jamais
-- une affaire deja renseignee, et seulement quand la source porte une vraie
-- affaire (ID > 1, l'affaire « Indefini » n'en est pas une).
--
--   sh scripts/oc-psql.sh -f sql/reprise-affaire-transfert.sql
--
-- Tout est dans une transaction : en cas de doute, remplacer COMMIT par
-- ROLLBACK a la fin.
--
-- Idempotent : rejouable autant de fois que voulu.

BEGIN;

\echo '=== 1. Saisies d achat : SOURCE / IDSOURCE ==='
UPDATE "OpenConcerto42"."SAISIE_ACHAT"
   SET "ID_AFFAIRE" = "COMMANDE"."ID_AFFAIRE"
  FROM "OpenConcerto42"."COMMANDE"
 WHERE "SAISIE_ACHAT"."SOURCE" = 'COMMANDE'
   AND "SAISIE_ACHAT"."IDSOURCE" = "COMMANDE"."ID"
   AND ("SAISIE_ACHAT"."ID_AFFAIRE" IS NULL OR "SAISIE_ACHAT"."ID_AFFAIRE" = 1)
   AND "COMMANDE"."ID_AFFAIRE" > 1;

UPDATE "OpenConcerto42"."SAISIE_ACHAT"
   SET "ID_AFFAIRE" = "BON_RECEPTION"."ID_AFFAIRE"
  FROM "OpenConcerto42"."BON_RECEPTION"
 WHERE "SAISIE_ACHAT"."SOURCE" = 'BON_RECEPTION'
   AND "SAISIE_ACHAT"."IDSOURCE" = "BON_RECEPTION"."ID"
   AND ("SAISIE_ACHAT"."ID_AFFAIRE" IS NULL OR "SAISIE_ACHAT"."ID_AFFAIRE" = 1)
   AND "BON_RECEPTION"."ID_AFFAIRE" > 1;

\echo '=== 2. Documents : via les tables de transfert du coeur ==='

-- Factures fournisseur depuis une commande
UPDATE "OpenConcerto42"."FACTURE_FOURNISSEUR"
   SET "ID_AFFAIRE" = "COMMANDE"."ID_AFFAIRE"
  FROM "OpenConcerto42"."TR_COMMANDE"
  JOIN "OpenConcerto42"."COMMANDE" ON "COMMANDE"."ID" = "TR_COMMANDE"."ID_COMMANDE"
 WHERE "TR_COMMANDE"."ID_FACTURE_FOURNISSEUR" = "FACTURE_FOURNISSEUR"."ID"
   AND ("FACTURE_FOURNISSEUR"."ID_AFFAIRE" IS NULL OR "FACTURE_FOURNISSEUR"."ID_AFFAIRE" = 1)
   AND "COMMANDE"."ID_AFFAIRE" > 1;

-- Factures fournisseur depuis un bon de reception
UPDATE "OpenConcerto42"."FACTURE_FOURNISSEUR"
   SET "ID_AFFAIRE" = "BON_RECEPTION"."ID_AFFAIRE"
  FROM "OpenConcerto42"."TR_BON_RECEPTION"
  JOIN "OpenConcerto42"."BON_RECEPTION" ON "BON_RECEPTION"."ID" = "TR_BON_RECEPTION"."ID_BON_RECEPTION"
 WHERE "TR_BON_RECEPTION"."ID_FACTURE_FOURNISSEUR" = "FACTURE_FOURNISSEUR"."ID"
   AND ("FACTURE_FOURNISSEUR"."ID_AFFAIRE" IS NULL OR "FACTURE_FOURNISSEUR"."ID_AFFAIRE" = 1)
   AND "BON_RECEPTION"."ID_AFFAIRE" > 1;

-- Bons de reception depuis une commande
UPDATE "OpenConcerto42"."BON_RECEPTION"
   SET "ID_AFFAIRE" = "COMMANDE"."ID_AFFAIRE"
  FROM "OpenConcerto42"."TR_COMMANDE"
  JOIN "OpenConcerto42"."COMMANDE" ON "COMMANDE"."ID" = "TR_COMMANDE"."ID_COMMANDE"
 WHERE "TR_COMMANDE"."ID_BON_RECEPTION" = "BON_RECEPTION"."ID"
   AND ("BON_RECEPTION"."ID_AFFAIRE" IS NULL OR "BON_RECEPTION"."ID_AFFAIRE" = 1)
   AND "COMMANDE"."ID_AFFAIRE" > 1;

-- Avoirs fournisseurs depuis une saisie d'achat
UPDATE "OpenConcerto42"."AVOIR_FOURNISSEUR"
   SET "ID_AFFAIRE" = "SAISIE_ACHAT"."ID_AFFAIRE"
  FROM "OpenConcerto42"."TR_SAISIE_ACHAT"
  JOIN "OpenConcerto42"."SAISIE_ACHAT" ON "SAISIE_ACHAT"."ID" = "TR_SAISIE_ACHAT"."ID_SAISIE_ACHAT"
 WHERE "TR_SAISIE_ACHAT"."ID_AVOIR_FOURNISSEUR" = "AVOIR_FOURNISSEUR"."ID"
   AND ("AVOIR_FOURNISSEUR"."ID_AFFAIRE" IS NULL OR "AVOIR_FOURNISSEUR"."ID_AFFAIRE" = 1)
   AND "SAISIE_ACHAT"."ID_AFFAIRE" > 1;

-- Commandes clients depuis un devis
UPDATE "OpenConcerto42"."COMMANDE_CLIENT"
   SET "ID_AFFAIRE" = "DEVIS"."ID_AFFAIRE"
  FROM "OpenConcerto42"."TR_DEVIS"
  JOIN "OpenConcerto42"."DEVIS" ON "DEVIS"."ID" = "TR_DEVIS"."ID_DEVIS"
 WHERE "TR_DEVIS"."ID_COMMANDE_CLIENT" = "COMMANDE_CLIENT"."ID"
   AND ("COMMANDE_CLIENT"."ID_AFFAIRE" IS NULL OR "COMMANDE_CLIENT"."ID_AFFAIRE" = 1)
   AND "DEVIS"."ID_AFFAIRE" > 1;

-- Factures de vente depuis un devis
UPDATE "OpenConcerto42"."SAISIE_VENTE_FACTURE"
   SET "ID_AFFAIRE" = "DEVIS"."ID_AFFAIRE"
  FROM "OpenConcerto42"."TR_DEVIS"
  JOIN "OpenConcerto42"."DEVIS" ON "DEVIS"."ID" = "TR_DEVIS"."ID_DEVIS"
 WHERE "TR_DEVIS"."ID_SAISIE_VENTE_FACTURE" = "SAISIE_VENTE_FACTURE"."ID"
   AND ("SAISIE_VENTE_FACTURE"."ID_AFFAIRE" IS NULL OR "SAISIE_VENTE_FACTURE"."ID_AFFAIRE" = 1)
   AND "DEVIS"."ID_AFFAIRE" > 1;

-- Factures de vente depuis une commande client
UPDATE "OpenConcerto42"."SAISIE_VENTE_FACTURE"
   SET "ID_AFFAIRE" = "COMMANDE_CLIENT"."ID_AFFAIRE"
  FROM "OpenConcerto42"."TR_COMMANDE_CLIENT"
  JOIN "OpenConcerto42"."COMMANDE_CLIENT" ON "COMMANDE_CLIENT"."ID" = "TR_COMMANDE_CLIENT"."ID_COMMANDE_CLIENT"
 WHERE "TR_COMMANDE_CLIENT"."ID_SAISIE_VENTE_FACTURE" = "SAISIE_VENTE_FACTURE"."ID"
   AND ("SAISIE_VENTE_FACTURE"."ID_AFFAIRE" IS NULL OR "SAISIE_VENTE_FACTURE"."ID_AFFAIRE" = 1)
   AND "COMMANDE_CLIENT"."ID_AFFAIRE" > 1;

-- Bons de livraison depuis une commande client
UPDATE "OpenConcerto42"."BON_DE_LIVRAISON"
   SET "ID_AFFAIRE" = "COMMANDE_CLIENT"."ID_AFFAIRE"
  FROM "OpenConcerto42"."TR_COMMANDE_CLIENT"
  JOIN "OpenConcerto42"."COMMANDE_CLIENT" ON "COMMANDE_CLIENT"."ID" = "TR_COMMANDE_CLIENT"."ID_COMMANDE_CLIENT"
 WHERE "TR_COMMANDE_CLIENT"."ID_BON_DE_LIVRAISON" = "BON_DE_LIVRAISON"."ID"
   AND ("BON_DE_LIVRAISON"."ID_AFFAIRE" IS NULL OR "BON_DE_LIVRAISON"."ID_AFFAIRE" = 1)
   AND "COMMANDE_CLIENT"."ID_AFFAIRE" > 1;

-- Avoirs clients depuis une facture de vente
UPDATE "OpenConcerto42"."AVOIR_CLIENT"
   SET "ID_AFFAIRE" = "SAISIE_VENTE_FACTURE"."ID_AFFAIRE"
  FROM "OpenConcerto42"."TR_SAISIE_VENTE_FACTURE"
  JOIN "OpenConcerto42"."SAISIE_VENTE_FACTURE" ON "SAISIE_VENTE_FACTURE"."ID" = "TR_SAISIE_VENTE_FACTURE"."ID_SAISIE_VENTE_FACTURE"
 WHERE "TR_SAISIE_VENTE_FACTURE"."ID_AVOIR_CLIENT" = "AVOIR_CLIENT"."ID"
   AND ("AVOIR_CLIENT"."ID_AFFAIRE" IS NULL OR "AVOIR_CLIENT"."ID_AFFAIRE" = 1)
   AND "SAISIE_VENTE_FACTURE"."ID_AFFAIRE" > 1;

\echo '=== 3. Lignes : elles reprennent l affaire de leur document ==='

UPDATE "OpenConcerto42"."COMMANDE_ELEMENT"
   SET "ID_AFFAIRE" = "COMMANDE"."ID_AFFAIRE"
  FROM "OpenConcerto42"."COMMANDE"
 WHERE "COMMANDE_ELEMENT"."ID_COMMANDE" = "COMMANDE"."ID"
   AND ("COMMANDE_ELEMENT"."ID_AFFAIRE" IS NULL OR "COMMANDE_ELEMENT"."ID_AFFAIRE" = 1)
   AND "COMMANDE"."ID_AFFAIRE" > 1;

UPDATE "OpenConcerto42"."BON_RECEPTION_ELEMENT"
   SET "ID_AFFAIRE" = "BON_RECEPTION"."ID_AFFAIRE"
  FROM "OpenConcerto42"."BON_RECEPTION"
 WHERE "BON_RECEPTION_ELEMENT"."ID_BON_RECEPTION" = "BON_RECEPTION"."ID"
   AND ("BON_RECEPTION_ELEMENT"."ID_AFFAIRE" IS NULL OR "BON_RECEPTION_ELEMENT"."ID_AFFAIRE" = 1)
   AND "BON_RECEPTION"."ID_AFFAIRE" > 1;

UPDATE "OpenConcerto42"."FACTURE_FOURNISSEUR_ELEMENT"
   SET "ID_AFFAIRE" = "FACTURE_FOURNISSEUR"."ID_AFFAIRE"
  FROM "OpenConcerto42"."FACTURE_FOURNISSEUR"
 WHERE "FACTURE_FOURNISSEUR_ELEMENT"."ID_FACTURE_FOURNISSEUR" = "FACTURE_FOURNISSEUR"."ID"
   AND ("FACTURE_FOURNISSEUR_ELEMENT"."ID_AFFAIRE" IS NULL OR "FACTURE_FOURNISSEUR_ELEMENT"."ID_AFFAIRE" = 1)
   AND "FACTURE_FOURNISSEUR"."ID_AFFAIRE" > 1;

UPDATE "OpenConcerto42"."SAISIE_ACHAT_ELEMENT"
   SET "ID_AFFAIRE" = "SAISIE_ACHAT"."ID_AFFAIRE"
  FROM "OpenConcerto42"."SAISIE_ACHAT"
 WHERE "SAISIE_ACHAT_ELEMENT"."ID_SAISIE_ACHAT" = "SAISIE_ACHAT"."ID"
   AND ("SAISIE_ACHAT_ELEMENT"."ID_AFFAIRE" IS NULL OR "SAISIE_ACHAT_ELEMENT"."ID_AFFAIRE" = 1)
   AND "SAISIE_ACHAT"."ID_AFFAIRE" > 1;

UPDATE "OpenConcerto42"."COMMANDE_CLIENT_ELEMENT"
   SET "ID_AFFAIRE" = "COMMANDE_CLIENT"."ID_AFFAIRE"
  FROM "OpenConcerto42"."COMMANDE_CLIENT"
 WHERE "COMMANDE_CLIENT_ELEMENT"."ID_COMMANDE_CLIENT" = "COMMANDE_CLIENT"."ID"
   AND ("COMMANDE_CLIENT_ELEMENT"."ID_AFFAIRE" IS NULL OR "COMMANDE_CLIENT_ELEMENT"."ID_AFFAIRE" = 1)
   AND "COMMANDE_CLIENT"."ID_AFFAIRE" > 1;

UPDATE "OpenConcerto42"."SAISIE_VENTE_FACTURE_ELEMENT"
   SET "ID_AFFAIRE" = "SAISIE_VENTE_FACTURE"."ID_AFFAIRE"
  FROM "OpenConcerto42"."SAISIE_VENTE_FACTURE"
 WHERE "SAISIE_VENTE_FACTURE_ELEMENT"."ID_SAISIE_VENTE_FACTURE" = "SAISIE_VENTE_FACTURE"."ID"
   AND ("SAISIE_VENTE_FACTURE_ELEMENT"."ID_AFFAIRE" IS NULL OR "SAISIE_VENTE_FACTURE_ELEMENT"."ID_AFFAIRE" = 1)
   AND "SAISIE_VENTE_FACTURE"."ID_AFFAIRE" > 1;

COMMIT;

